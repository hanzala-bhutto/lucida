/**
 * Every word Lucida shows, in German and English. The language is a setting
 * ("System" follows Windows); pure layouts get it as a parameter, the UI reads
 * it from the settings.
 */
export type Lang = "de" | "en";
export type LangPref = "system" | Lang;

export function resolveLang(pref: LangPref | undefined): Lang {
  if (pref === "de" || pref === "en") return pref;
  const nav = typeof navigator !== "undefined" ? navigator.language : "en";
  return nav.toLowerCase().startsWith("de") ? "de" : "en";
}

